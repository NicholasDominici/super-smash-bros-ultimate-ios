#!/usr/bin/env python3
"""Embed native module templates as signed code and copy-on-write data.

Static NSOs retain their three legacy sections. Cataloged NRO templates share
one x0 section, one x1 section, and one RW segment, with per-module start labels.
This keeps Mach-O section indexes below their 8-bit limit for Smash's 98 NROs.
Runtime reconstructs each original image using signed-page vm_remap.
"""
import json
import re
import sys
from pathlib import Path

PG = 0x4000


def r16(value):
    return (value + PG - 1) & ~(PG - 1)


def module_parts(directory, name):
    """Return the three template file ranges, validating signed-page layout."""
    if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]{0,7}', name):
        raise ValueError(f'Invalid embedded module identifier: {name!r}')
    path = Path(directory)
    header = dict(line[2:].split() for line in (path / f'{name}.fixups.tsv').read_text().splitlines())
    te, po = int(header['TEXT_END'], 16), int(header['PATCH_OFF'], 16)
    ko, ks = int(header['KEY_PAGE_OFF'], 16), int(header['KEY_PAGE_SIZE'], 16)
    binary = path / f'{name}.patched.bin'
    size = binary.stat().st_size
    a, end = r16(te), r16(size)
    if po < 0:
        fl = int(header['FILE_IMAGE_LEN'], 16)
        if fl % PG or a > fl or ko % PG or ks != PG or ko < fl or size < fl:
            raise ValueError(f'{name}: invalid front-patch module layout')
        parts = ((0, a), (a, fl), (fl, end))
    else:
        if po % PG or a > ko or ko + ks > po or ko % PG or ks != PG or size < po:
            raise ValueError(f'{name}: invalid appended-patch module layout')
        parts = ((0, a), (a, po), (po, end))
    if any(hi < lo or lo > size for lo, hi in parts):
        raise ValueError(f'{name}: template range exceeds its image')
    return binary.resolve(), size, parts


def generate(directory, destination, names):
    """Write assembly and return linker flags for the writable templates."""
    path = Path(directory)
    if len(set(names)) != len(names):
        raise ValueError('Duplicate embedded module identifier')
    dynamic = set()
    catalog = path / 'nro_catalog.json'
    if catalog.exists():
        metadata = json.loads(catalog.read_text())
        entries = metadata.get('modules', [])
        dynamic = {entry['name'] for entry in entries}
        if len(dynamic) != len(entries) or len(dynamic) > 512 or any(not re.fullmatch(r'n[0-9a-f]{7}', n) for n in dynamic):
            raise ValueError('Invalid dynamic module catalog')
        if not metadata.get('rewritten') or not dynamic.issubset(names):
            raise ValueError('Every cataloged NRO must be rewritten and included in the signed executable')
    layouts = {name: module_parts(path, name) for name in names}
    asm = ['// Generated by dm/ios/tools/gen_embed.py; do not edit']
    flags = []

    def emit(section, name, part, label=None):
        binary, size, ranges = layouts[name]
        lo, hi = ranges[part]
        # .incbin uses a quoted assembler path; reject line/quote injection.
        quoted = str(binary)
        if any(c in quoted for c in ('"', '\\', '\n', '\r')):
            raise ValueError('Embedded binary path contains unsupported assembler characters')
        asm.extend([f'    .section {section}', '    .p2align 14'])
        if label:
            asm.extend([f'    .globl _{label}', f'    .private_extern _{label}', f'_{label}:'])
        fill = max(0, min(hi, size) - lo)
        if fill:
            asm.append(f'    .incbin "{quoted}", {lo:#x}, {fill:#x}')
        if hi - lo > fill:
            asm.append(f'    .space {hi - lo - fill:#x}')
        asm.append('    .p2align 14')

    for name in names:
        if name in dynamic:
            continue
        sections = (f'__TEXT,__dm{name}x0', f'__DM{name}W,__img', f'__TEXT,__dm{name}x1')
        for part, section in enumerate(sections):
            if any(len(x) > 16 for x in section.split(',')):
                raise ValueError('Static Mach-O section identifier exceeds 16 bytes')
            emit(section, name, part)
        flags.append(f'-Wl,-segprot,__DM{name}W,rw,rw')
    if dynamic:
        for part, (section, suffix) in enumerate((('__TEXT,__dmnrox0', 'x0'), ('__DMNROW,__img', 'w'), ('__TEXT,__dmnrox1', 'x1'))):
            for name in names:
                if name in dynamic:
                    sizes = next(entry for entry in entries if entry['name'] == name).get('embed_sizes')
                    actual = [hi - lo for lo, hi in layouts[name][2]]
                    if sizes != actual:
                        raise ValueError(f'{name}: catalog template sizes do not match rewritten image')
                    emit(section, name, part, f'dm_nro_{name}_{suffix}')
        flags.append('-Wl,-segprot,__DMNROW,rw,rw')
    Path(destination).write_text('\n'.join(asm) + '\n')
    return flags


def main():
    if len(sys.argv) < 4:
        raise SystemExit('usage: gen_embed.py <patched-dir> <output.S> <module...>')
    print(' '.join(generate(sys.argv[1], sys.argv[2], sys.argv[3:])))


if __name__ == '__main__':
    main()
